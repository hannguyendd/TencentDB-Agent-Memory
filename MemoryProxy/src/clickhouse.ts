// ════════════════════════════════════════════════════════════════════════════
// Skill Usage Telemetry — default-task activity recall instrumentation
// Design: docs/design/2026-09-09-skill-usage-telemetry-and-default-task-recall.md
//
// Instrumented only on the two real usage signals, LLM-initiated view/search_hit; not on
// `<available_skills>` injection (avoids a self-loop: recall -> injection -> instrumentation -> higher score -> more recall).
//
// Hard constraints (same as session_init_logs / tool_call_logs):
//   1. writeSkillUsageRow returns void synchronously and never throws
//   2. flush/requeue are fully silent
//   3. CH not configured (disabled=true) -> no-op, main path unaware
// ════════════════════════════════════════════════════════════════════════════

/** Raw shape passed in by instrumentation points (not truncated/hashed). */
export interface SkillUsageLogInput {
  timestamp: string;                   // ISO 8601 UTC
  spaceId?: string;
  teamId?: string;
  agentId?: string;
  userId?: string;
  sessionKey?: string;
  /** 'view' | 'search_hit' -- to add 'patch_hit' etc. later, extend the enum. */
  eventType: string;
  skillId: string;
  agentSource?: string;                // claude-code/codebuddy/codex/...
}

/** Final shape of one row of the CH `skill_usage_logs` table. */
export interface SkillUsageLogRow {
  timestamp: string;
  space_id: string;
  team_id: string;
  agent_id: string;
  user_id: string;
  session_key: string;
  event_type: string;
  skill_id: string;
  agent_source: string;
  source_tag: string;
  host: string;
}

/** Build a skill_usage row; pure function for ease of unit testing. */
export function buildSkillUsageLogRow(input: SkillUsageLogInput): SkillUsageLogRow {
  return {
    timestamp: toChTimestamp(input.timestamp),
    space_id: input.spaceId ?? "",
    team_id: input.teamId ?? "",
    agent_id: input.agentId ?? "",
    user_id: input.userId ?? "",
    session_key: input.sessionKey ?? "",
    event_type: input.eventType,
    skill_id: input.skillId,
    agent_source: input.agentSource ?? "",
    source_tag: "proxy",
    host: HOST_ID,
  };
}

let skillUsageBuffer: SkillUsageLogRow[] = [];

function requeueSkillUsage(rows: SkillUsageLogRow[]): void {
  skillUsageBuffer = requeueWithOverflowGuard(
    skillUsageBuffer,
    rows,
    "clickhouse.skillUsage.overflow",
  );
}

async function flushSkillUsage(): Promise<void> {
  await flushBuffer(
    skillUsageBuffer,
    client,
    SKILL_USAGE_TABLE,
    requeueSkillUsage,
    "clickhouse.skillUsage",
  );
}

/**
 * Write one skill_usage record (fire-and-forget, never throws).
 * No-op when CH is not configured/uninitialized; construction exceptions are swallowed silently.
 *
 * `skill_id` is skipped outright when it is an empty string (defensive: the MRR aggregation key cannot be empty).
 */
export function writeSkillUsageRow(input: SkillUsageLogInput): void {
  if (disabled || !config) return;
  if (!input.skillId) return;
  try {
    const row = buildSkillUsageLogRow(input);
    enqueueRow(
      skillUsageBuffer,
      row,
      flushSkillUsage,
      config?.flushThreshold ?? 50,
    );
  } catch {
    // Never block the business
  }
}

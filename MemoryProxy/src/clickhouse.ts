/**
 * Initialize the ClickHouse writer.
 * Must be called once at startup. Idempotent.
 */
export function initClickHouse(cfg: ClickHouseConfig): void {
  if (!cfg.enabled) {
    disabled = true;
    return;
  }
  if (!cfg.url) {
    log.warn("clickhouse.init.skipped", { reason: "empty url" });
    disabled = true;
    return;
  }

  config = cfg;
  disabled = false;

  // Periodic flush (both main and raw buffers)
  flushTimer = setInterval(() => {
    void flush();
    void flushRaw();
    // Internal telemetry buffers (§7.1) — silent fallback to prevent unhandledRejection
    void flushSessionInit().catch(() => {});
    void flushToolCall().catch(() => {});
    // skill_usage_logs (2026-09-09 skill usage telemetry) -- same as above;
    // without this timed flush, in light-load scenarios (< flushThreshold rows/period) data would
    // stay stuck in the buffer until shutdown before being persisted, causing severe lag.
    void flushSkillUsage().catch(() => {});
  }, cfg.flushIntervalMs);
  flushTimer.unref(); // Don't prevent process exit

  log.info("clickhouse.init", {
    url: cfg.url,
    database: cfg.database,
    table: cfg.table,
    flushIntervalMs: cfg.flushIntervalMs,
    flushThreshold: cfg.flushThreshold,
    ttlDays: cfg.ttlDays,
  });

  // Fire-and-forget: create client + database + table (idempotent)
  ensureClickHouse(cfg).catch((err: unknown) => {
    log.warn("clickhouse.init.ensureFailed", {
      error: err instanceof Error ? err.message : String(err),
    });
  });
}

/**
 * Create the SDK client (against the `default` db for DDL), ensure database +
 * table exist, then re-point the client at the target database for inserts.
 */
async function ensureClickHouse(cfg: ClickHouseConfig): Promise<void> {
  const { createClient } = await import("@clickhouse/client");

  // Bootstrap client (no database bound) to create the target database.
  const bootstrap = createClient({
    url: cfg.url,
    username: cfg.user,
    password: cfg.password,
    request_timeout: 10_000,
  });

  try {
    await bootstrap.command({
      query: `CREATE DATABASE IF NOT EXISTS ${cfg.database}`,
      clickhouse_settings: { wait_end_of_query: 1 },
    });
  } finally {
    await bootstrap.close().catch(() => {});
  }

  // Target client bound to the database, reused for all inserts.
  client = createClient({
    url: cfg.url,
    username: cfg.user,
    password: cfg.password,
    database: cfg.database,
    request_timeout: 10_000,
    keep_alive: { enabled: true },
  });

  const ttlClause = cfg.ttlDays > 0 ? `TTL timestamp + INTERVAL ${cfg.ttlDays} DAY` : "";
  const ddl = [
    `CREATE TABLE IF NOT EXISTS ${cfg.table} (`,
    "  timestamp DateTime64(3, 'Asia/Shanghai'),",
    "  event LowCardinality(String),",
    "  session_key String,",
    "  turn_seq UInt32,",
    "  user_input String,",
    "  model_id String,",
    "  model_name String DEFAULT '',",
    "  user_id String,",
    "  upstream_url String,",
    "  stream UInt8,",
    "  prompt_tokens UInt64,",
    "  completion_tokens UInt64,",
    "  total_tokens UInt64,",
    "  cache_hit_tokens UInt64,",
    "  cache_miss_tokens UInt64,",
    "  cache_write_tokens UInt64,",
    "  input_tokens UInt64 DEFAULT 0,",
    "  cache_creation_ephemeral_5m_input_tokens UInt64 DEFAULT 0,",
    "  cache_creation_ephemeral_1h_input_tokens UInt64 DEFAULT 0,",
    "  credit Float64,",
    "  credit_saved Float64 DEFAULT 0,",
    "  routed_from LowCardinality(String),",
    "  space_id String DEFAULT '',",
    "  source_tag LowCardinality(String) DEFAULT 'proxy',",
    "  host LowCardinality(String),",
    "  upstream_request_id String DEFAULT '',",
    "  compress_tokens_saved UInt64 DEFAULT 0,",
    "  pre_compress_tokens UInt64 DEFAULT 0,",
    "  post_compress_tokens UInt64 DEFAULT 0,",
    "  compress_remote_count UInt64 DEFAULT 0,",
    "  compress_remote_total_ms UInt64 DEFAULT 0",
    ") ENGINE = MergeTree()",
    "ORDER BY (user_id, session_key, timestamp)",
    ttlClause,
  ]
    .filter(Boolean)
    .join("\n");

  await client.command({
    query: ddl,
    clickhouse_settings: { wait_end_of_query: 1 },
  });

  // Raw usage table (traceability for non-TokenHub / unrecognized format).
  if (cfg.rawTable) {
    // New tables use user_id as the default sort key (aligned with the main table); old tables keep key_id (just backfill the user_id column in migrate)
    const rawDdl = [
      `CREATE TABLE IF NOT EXISTS ${cfg.rawTable} (`,
      "  timestamp DateTime64(3, 'Asia/Shanghai'),",
      "  model_id String,",
      "  model_name String DEFAULT '',",
      "  key_id LowCardinality(String),",
      "  user_id String DEFAULT '',",
      "  session_key String,",
      "  turn_seq UInt32 DEFAULT 0,",
      "  user_input String DEFAULT '',",
      "  upstream_url String,",
      "  stream UInt8,",
      "  usage String,",
      "  reason LowCardinality(String),",
      "  routed_from String DEFAULT '',",
      "  space_id String DEFAULT '',",
      "  source_tag LowCardinality(String) DEFAULT 'proxy',",
      "  host LowCardinality(String),",
      "  upstream_request_id String DEFAULT ''",
      ") ENGINE = MergeTree()",
      "ORDER BY (user_id, timestamp)",
      ttlClause,
    ]
      .filter(Boolean)
      .join("\n");

    await client.command({
      query: rawDdl,
      clickhouse_settings: { wait_end_of_query: 1 },
    });
  }

  // Backfill historical schema drift: run ALTER TABLE ADD COLUMN IF NOT EXISTS on existing tables.
  // Idempotent and non-blocking on failure (downgrades to warn when DDL permission is missing; the business keeps using writable fields).
  await migrateSchema(client, cfg);

  // Internal Usage Telemetry (§7.1) — idempotently register the two new tables' DDL.
  // Failure does not block startup: separate try/catch, log warn and continue (same failure-degradation approach as the old tables).
  try {
    await createTableIfNotExists(client, sessionInitTableDdl());
    await createTableIfNotExists(client, toolCallTableDdl());
    await createTableIfNotExists(client, skillUsageTableDdl());
    log.info("clickhouse.init.telemetryTableReady", {
      sessionInitTable: `${cfg.database}.${SESSION_INIT_TABLE}`,
      toolCallTable: `${cfg.database}.${TOOL_CALL_TABLE}`,
      skillUsageTable: `${cfg.database}.${SKILL_USAGE_TABLE}`,
      ttlDays: TELEMETRY_TTL_DAYS,
      skillUsageTtlDays: SKILL_USAGE_TTL_DAYS,
    });
  } catch (err: unknown) {
    log.warn("clickhouse.init.telemetryTableFailed", {
      error: err instanceof Error ? err.message : String(err),
    });
  }

  log.info("clickhouse.init.tableReady", {
    table: `${cfg.database}.${cfg.table}`,
    rawTable: cfg.rawTable ? `${cfg.database}.${cfg.rawTable}` : undefined,
    ttlDays: cfg.ttlDays,
  });
}

/**
 * Backfill historical drift in the ClickHouse table schema.
 *
 * `CREATE TABLE IF NOT EXISTS` only runs DDL when the table does not exist; once a table is created, later field changes
 * in the code's DDL (new columns, type adjustments) cannot sync to live tables automatically. This function iterates an
 * explicit migration list and runs `ALTER TABLE ADD COLUMN IF NOT EXISTS` for each target table.
 *
 * Properties:
 *  - **Idempotent**: `IF NOT EXISTS` is guaranteed natively by ClickHouse (>=20.3); repeated runs cost nothing
 *  - **Failure degradation**: a single-column ALTER failure (e.g. app account lacks ALTER permission) -> only log warn,
 *    continue with the remaining columns; the startup flow is not interrupted
 *  - **Change audit**: finally emit a `clickhouse.migrate.done` summary log
 *
 * This function is called after `CREATE TABLE IF NOT EXISTS` in `initClickHouse`;
 * it is a no-op for brand-new tables (columns are already defined in CREATE) and backfills for existing old tables.
 *
 * @exported for unit testing.
 */
export async function migrateSchema(
  client: ClickHouseClient,
  cfg: ClickHouseConfig,
): Promise<void> {
  const migrations: Array<{ table: string; column: string; type: string }> = [
    // usage_logs: backfill the main table (historical debt + the newly added model_name)
    { table: cfg.table, column: "session_key", type: "String" },
    { table: cfg.table, column: "turn_seq", type: "UInt32 DEFAULT 0" },
    { table: cfg.table, column: "user_input", type: "String DEFAULT ''" },
    { table: cfg.table, column: "user_id", type: "String DEFAULT ''" },
    { table: cfg.table, column: "model_name", type: "String DEFAULT ''" },
    { table: cfg.table, column: "input_tokens", type: "UInt64 DEFAULT 0" },
    {
      table: cfg.table,
      column: "cache_creation_ephemeral_5m_input_tokens",
      type: "UInt64 DEFAULT 0",
    },
    {
      table: cfg.table,
      column: "cache_creation_ephemeral_1h_input_tokens",
      type: "UInt64 DEFAULT 0",
    },
    { table: cfg.table, column: "credit_saved", type: "Float64 DEFAULT 0" },
    { table: cfg.table, column: "space_id", type: "String DEFAULT ''" },
    {
      table: cfg.table,
      column: "source_tag",
      type: "LowCardinality(String) DEFAULT 'proxy'",
    },
    // Upstream response header `x-request-id` (returned by OpenAI/Anthropic-compatible gateways such as tokenhub).
    // Newly added: for cross-system tracing (client x-request-id -> our upstream_request_id -> upstream logs).
    { table: cfg.table, column: "upstream_request_id", type: "String DEFAULT ''" },
    // cost-guard tokens saved by compression: max(0, preCompressTokens − postCompressTokens)
    { table: cfg.table, column: "compress_tokens_saved", type: "UInt64 DEFAULT 0" },
    // Raw counts before/after compression, used to compute the compression ratio -- the difference alone cannot yield the denominator.
    { table: cfg.table, column: "pre_compress_tokens", type: "UInt64 DEFAULT 0" },
    { table: cfg.table, column: "post_compress_tokens", type: "UInt64 DEFAULT 0" },
    // Actual number of compression service calls and total duration; together they give a cross-request weighted average duration.
    { table: cfg.table, column: "compress_remote_count", type: "UInt64 DEFAULT 0" },
    { table: cfg.table, column: "compress_remote_total_ms", type: "UInt64 DEFAULT 0" },
  ];

  // usage_raw: backfill the trace table (6 new columns + model_name + upstream_request_id)
  if (cfg.rawTable) {
    migrations.push(
      { table: cfg.rawTable, column: "user_id", type: "String DEFAULT ''" },
      { table: cfg.rawTable, column: "model_name", type: "String DEFAULT ''" },
      { table: cfg.rawTable, column: "turn_seq", type: "UInt32 DEFAULT 0" },
      { table: cfg.rawTable, column: "user_input", type: "String DEFAULT ''" },
      { table: cfg.rawTable, column: "routed_from", type: "String DEFAULT ''" },
      { table: cfg.rawTable, column: "space_id", type: "String DEFAULT ''" },
      {
        table: cfg.rawTable,
        column: "source_tag",
        type: "LowCardinality(String) DEFAULT 'proxy'",
      },
      {
        table: cfg.rawTable,
        column: "upstream_request_id",
        type: "String DEFAULT ''",
      },
    );
  }

  // tool_call_logs: add the reject_reason column (existing tables get it via ALTER at this release)
  migrations.push({
    table: TOOL_CALL_TABLE,
    column: "reject_reason",
    type: "LowCardinality(String) DEFAULT ''",
  });

  let ok = 0;
  let failed = 0;
  for (const m of migrations) {
    try {
      await client.command({
        query: `ALTER TABLE ${m.table} ADD COLUMN IF NOT EXISTS ${m.column} ${m.type}`,
        clickhouse_settings: { wait_end_of_query: 1 },
      });
      ok++;
    } catch (err: unknown) {
      failed++;
      log.warn("clickhouse.migrate.column_failed", {
        table: m.table,
        column: m.column,
        err: err instanceof Error ? err.message : String(err),
      });
    }
  }
  log.info("clickhouse.migrate.done", {
    ok,
    failed,
    total: migrations.length,
  });
}

/** Target timezone offset (hours) for ClickHouse timestamps. 8 = China Standard Time (UTC+8). */
const CH_UTC_OFFSET_HOURS = 8;

/**
 * Convert an ISO 8601 UTC timestamp to a ClickHouse DateTime64 string in
 * China Standard Time (UTC+8).
 *
 * Callers generate timestamps with `new Date().toISOString()` (always UTC, with "Z").
 * The ClickHouse `timestamp` column is declared `DateTime64(3, 'Asia/Shanghai')`, and on write a
 * bare string without timezone is parsed as Asia/Shanghai. So here the UTC wall clock is first shifted forward 8 hours
 * to get the "Beijing wall-clock digits" -- after writing, the **absolute instant ClickHouse parses back is correct** (epoch unchanged),
 * and display and time functions (now() / toStartOfDay() / toDate()) all work in Beijing time.
 *
 * Input:  "2026-06-16T10:00:00.000Z"  (UTC)
 * Output: "2026-06-16 18:00:00.000"   (Beijing wall clock; the epoch parsed back by the column timezone = the original UTC instant)
 */
function toChTimestamp(iso: string): string {
  const ms = Date.parse(iso);
  if (Number.isNaN(ms)) {
    // On parse failure, fall back to bare formatting without offset (best effort not to lose data).
    return iso.replace("T", " ").replace("Z", "").slice(0, 23);
  }
  const shifted = new Date(ms + CH_UTC_OFFSET_HOURS * 60 * 60 * 1000);
  return shifted.toISOString().replace("T", " ").replace("Z", "").slice(0, 23);
}


/** One row = one upstream request (primary usage or extension telemetry). A turn is identified by (session_key, turn_seq). */
export interface ClickHouseRow {
  timestamp: string;       // ClickHouse DateTime64 format "YYYY-MM-DD HH:MM:SS.mmm"
  event: string;           // 'usage' | 'analyzer_usage' (extension telemetry)
  session_key: string;     // Session isolation key (used to merge turns)
  turn_seq: number;        // Turn sequence number
  user_input: string;      // User input of this turn (only set on the first request, after denoising; empty otherwise)
  model_id: string;
  model_name: string;      // UI display name (from pricing table modelName; falls back to modelId when unmatched)
  user_id: string;         // User identifier (user_id when auth is enabled, otherwise SHA-256(apiKey)[:8])
  upstream_url: string;
  stream: number;          // 0 or 1
  prompt_tokens: number;
  completion_tokens: number;
  total_tokens: number;
  cache_hit_tokens: number;    // Cache hits (cache_read)
  cache_miss_tokens: number;
  cache_write_tokens: number;  // Cache writes (cache_creation, total)
  // ── TokenHub Anthropic fields as-is (no conversion) ─────────────────────────
  input_tokens: number;                                  // Non-cached input (TokenHub already excludes cache)
  cache_creation_ephemeral_5m_input_tokens: number;      // 5m TTL cache writes
  cache_creation_ephemeral_1h_input_tokens: number;      // 1h TTL cache writes
  credit: number;
  credit_saved: number;        // Credit saved by routing (only set when event=usage and routed_from is non-empty)
  routed_from: string;
  space_id: string;            // Space/tenant identifier (extracted from the /proxy/<spaceId>/... path)
  source_tag: string;          // Source tag, always "proxy"
  host: string;
  upstream_request_id: string; // Upstream response header `x-request-id` (generated by tokenhub/OpenAI-compatible gateways), for cross-system tracing
  /**
   * Tokens saved by compression: max(0, pre_compress_tokens − post_compress_tokens).
   * From cost-guard extensionStats; 0 when not compressed.
   */
  compress_tokens_saved: number;
  /**
   * Pre-compression token count reported by the compression service (only counts content for which it actually returned a number).
   *
   * Note on units: this is counted by the compression service's own tokenizer and is not the same yardstick as the `input_tokens`
   * on the same row (the upstream model's billing basis); the two cannot be subtracted or converted directly into cost.
   * Its purpose is to compute the compression ratio `post / pre`.
   */
  pre_compress_tokens: number;
  /** Token count of the same batch of content after compression; items that keep their original text are recorded as equal to the pre-compression value. */
  post_compress_tokens: number;
  /** Number of times the compression model was actually called; cache hits and local skips are not counted. */
  compress_remote_count: number;
  /** Sum of actual compression model request durations (ms), used to compute a weighted average across requests. */
  compress_remote_total_ms: number;
}


/**
 * api/auth.ts - login verification + environment binding.
 *
 * Login flow:
 *   ① GET /meta/instances to choose an instance
 *   ② The user enters their own user_key (sk-mem-…)
 *   ③ POST /meta/auth/verify (Header only has X-Tdai-Service-Id, body carries user_key)
 *   ④ data.valid === true → login succeeds, the frontend writes { instance_id, user_key, user } into the session
 * No OAuth, no Cookie; see lib/panelSession.ts.
 */
import { request, metaCall } from './base';
import type { PublicUser } from './types';

export const authVerifyApi = {
  /** Login verification: Header carries only the instance ID, user_key goes only in the body (meta-api.openapi.yaml §auth/verify) */
  verify: (instanceId: string, userKey: string) =>
    metaCall<{ valid: boolean; user?: PublicUser }>(
      'auth/verify',
      { user_key: userKey },
      { 'X-Tdai-Service-Id': instanceId }
    ),
};

export interface AuthMethod {
  id: string;
  type: 'user_key' | 'woa';
  display_name: string;
  enabled: boolean;
}

/**
 * user_key login (compatible with user-held keys).
 *
 * Isomorphic to the two-step confirmation of the WOA flow: first preview to see "who this key belongs to", then login to confirm.
 * When the system has no such key, login uses it to create a new account (register on first login).
 *
 * Goes through the Panel instead of the frontend connecting to core directly: creating an account needs the instance admin credentials, which the frontend cannot get.
 */
export const userKeyLoginApi = {
  preview: (instanceId: string, userKey: string) =>
    request<{
      exists: boolean;
      user_id?: string;
      username?: string;
      display_name?: string;
      user_type?: string;
    }>('POST', '/api/v1/auth/user-key/preview', {
      instance_id: instanceId,
      user_key: userKey,
    }),
  login: (instanceId: string, userKey: string, username?: string) =>
    request<{
      authenticated: boolean;
      instance_id: string;
      user_id: string;
      user?: PublicUser;
      created: boolean;
    }>('POST', '/api/v1/auth/user-key/login', {
      instance_id: instanceId,
      user_key: userKey,
      username,
    }),
};

export const authMethodsApi = {
  list: () => request<{ methods: AuthMethod[] }>('GET', '/api/v1/auth/methods'),
  loginWoa: (instanceId: string, returnTo = '/') => {
    const params = new URLSearchParams({ instance_id: instanceId, return_to: returnTo });
    window.location.assign(`/api/v1/auth/idp/woa/login?${params.toString()}`);
  },
  session: (instanceId?: string) => {
    const query = instanceId ? `?instance_id=${encodeURIComponent(instanceId)}` : '';
    return request<{
      authenticated: boolean;
      method?: 'idp';
      instance_id?: string;
      user_id?: string;
      provider_id?: string;
      display_name?: string;
      user?: PublicUser;
      expires_at?: number;
      pending?: boolean;
      pending_identity?: {
        display_name?: string;
        login_name?: string;
        subject?: string;
      };
    }>('GET', `/api/v1/auth/session${query}`);
  },
  /**
   * Preview whether the user_key entered by the user already has a matching account in the system.
   * When exists=true, returns that account's info for the user to confirm "bind to it" or "create new".
   */
  previewWoaKey: (userKey: string) =>
    request<{
      exists: boolean;
      user_id?: string;
      username?: string;
      display_name?: string;
      user_type?: string;
    }>('POST', '/api/v1/auth/idp/woa/preview-key', { user_key: userKey }),
  completeWoa: (input: {
    username?: string;
    userKey?: string;
    customUserKey?: string;
  }) =>
    request<{
      authenticated: boolean;
      instance_id: string;
      user_id: string;
      user?: PublicUser;
      user_key?: string;
      user_key_autogenerated?: boolean;
    }>(
      'POST',
      '/api/v1/auth/idp/woa/complete',
      {
        username: input.username,
        // Both fields must be sent: the backend completePendingWoaLogin takes
        // `input.userKey || input.customUserKey`. Previously only custom_user_key was sent,
        // while the caller (LoginGate) passes userKey → the backend received an empty key →
        // 400 INVALID_USER_KEY, and the account creation request could never be sent.
        user_key: input.userKey,
        custom_user_key: input.customUserKey,
      },
    ),
  /**
   * Abandon the WOA pending-confirmation login and use user_key login instead.
   *
   * The backend clears the pending Cookie and issues a suppression flag: the gateway injects WOA identity headers on every request,
   * and if only pending were cleared, refreshing the page would immediately bounce back to the WOA confirmation page.
   */
  dismissWoa: () => request<{ ok: boolean }>('POST', '/api/v1/auth/idp/woa/dismiss'),

  /**
   * Undo dismiss and switch back to iOA login (clear the suppression flag).
   *
   * Paired with dismissWoa: called when the user clicks "Switch to iOA login" on the user_key page,
   * otherwise the previously set suppression flag would let the WOA ingress pass straight through and stay on the user_key form.
   */
  resumeWoa: () => request<{ ok: boolean }>('POST', '/api/v1/auth/idp/woa/resume'),
};

// ========================= Environment Bindings =========================
//
// ⚠️ The current deployment does not register /api/v1/users/* routes, so the following APIs may 404.
// The code is kept for compatibility with environments that still enable those routes; if a page depends on this group of APIs, first confirm the routes are registered.

/**
 * Environment binding (environment_bindings): associates the user's external user_id in an external environment (IDE / coding assistant, etc.)
 * with the platform user, so the proxy can reverse-lookup the team / agent / task
 * via (environment, environment_user_id).
 *
 * Uniqueness constraint: (environment, environment_user_id) is globally unique; occupied by someone else → 409.
 */
export interface EnvironmentBinding {
  id: string;
  user_id: string;
  environment: string;
  environment_user_id: string;
  created_at: string;
  updated_at: string;
}

export const environmentBindingsApi = {
  /** List all bindings of the current logged-in user */
  list: () => request<EnvironmentBinding[]>('GET', '/api/v1/users/me/environment-bindings'),

  /** Add a binding (idempotent: repeated POST of the same (env, env_user_id) by the same user does not error) */
  create: (data: { environment: string; environment_user_id: string }) =>
    request<EnvironmentBinding>('POST', '/api/v1/users/me/environment-bindings', data),

  /** Delete a binding (only your own; deleting someone else's → 403) */
  remove: (id: string) => request<{ ok: boolean }>('DELETE', `/api/v1/users/me/environment-bindings/${id}`),
};

/**
 * ClickHouse async batch writer for usage logs (official @clickhouse/client SDK).
 *
 * Positioning: **usage reporting to a self-hosted/cloud ClickHouse**, used to show each user's token consumption (per turn).
 * Independent of Langfuse / Opik reporting -- Langfuse does trace visualization, this is the usage/billing data source.
 *
 * Features:
 * - Official SDK (createClient + insert(JSONEachRow) + command(DDL))
 * - In-memory buffer + timed/threshold flush
 * - Failed rows are requeued (with a buffer cap to prevent OOM)
 * - Error-silent: never blocks or drags down business requests
 * - Graceful shutdown: flush the remaining buffer before exit
 *
 * Reliability note: failed rows are requeued and retried, but when the buffer exceeds its cap the oldest rows are dropped ("best effort" rather than
 * "never lose"). If billing requires zero loss, a disk-backed WAL must be added later -- not done at present.
 */


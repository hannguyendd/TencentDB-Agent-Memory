/**
 * Knowledge RPC port -- Wiki (15 endpoints) + Code-Graph (13 endpoints).
 *
 * Aligned with docs/knowledge/knowledge-api.yaml (finalized in 07/08/11). The control plane does not
 * persist wiki/code-graph; UI-triggered operations connect directly to core through this port.
 *
 * Addressing rules (strictly consistent with the yaml):
 *  - create / list / *write / *rm carry IdFields (team_id required, user_id optional);
 *  - get / ingest / delete / *ls / *read / graph / search and all code-graph
 *    query endpoints are addressed only by the asset id (wiki_id / code_graph_id), and no longer pass
 *    team/agent/user/task IDs (ownership is resolved by the kernel side via composite keys).
 */

// ── Wiki ──

export interface WikiDetail {
  wiki_id: string;
  team_id: string;
  name: string;
  /** null = manual upload; 'iwiki' etc. = external source (decides whether the detail page UI uses "Add files" or "Pull from external"). */
  source_type: string | null;
  /** External source URL; has a value only when source_type is non-null. */
  source_url: string | null;
  service_url: string | null;
  summary: string | null;
  status: 'draft' | 'pending' | 'processing' | 'ready' | 'failed';
  internal_status?: string | null;
  sync_error: string | null;
  version: string;
  owner_user_id: string | null;
  page_count: number | null;
  last_sync_at: string | null;
  created_at: string;
  updated_at: string;
}

export interface WikiListResult {
  items: WikiDetail[];
  total: number;
}

export interface WikiIngestResult {
  wiki_id: string;
  /** Design 2026-09-21 §3.3: adds the 'cancelling' intermediate state (old task being cancelled, new task already queued). */
  status: string;
  /** true = there was an in-flight task; after cancelling the old task via onBusy:'replace', a new task was queued. */
  queued?: boolean;
}

/** raw source file item (from a `raw/sources/` filesystem stat). */
export interface RawFileEntry {
  filename: string;
  size: number;
  uploaded_at: string;
}

/** processed page item (pages generated by ingest under `wiki/`). */
export interface PageEntry {
  id: string;
  title: string;
  type: string;
  path: string;
  locked?: boolean;
}

export interface WikiRawReadItem {
  filename: string;
  content?: string;
  not_found?: boolean;
}

export interface WikiRawWriteFile {
  filename: string;
  content: string;
}

export interface WikiRawWriteItem {
  filename: string;
  size: number;
}

export interface WikiRawRmResult {
  deleted_files: string[];
  deleted_pages: string[];
  rewritten_pages: number;
}

export interface WikiPageReadItem {
  ref: string;
  content?: string;
  not_found?: boolean;
}

export interface WikiPageWriteItem {
  ref: string;
  content: string;
}

export interface WikiPageWriteResultItem {
  ref: string;
  locked_injected?: boolean;
}

export interface WikiPageRmResult {
  deleted_pages: string[];
  rewritten_files: number;
}

export interface WikiGraphData {
  nodes: any[];
  edges: any[];
  communities?: any[];
}

export interface WikiSearchResult {
  results: Array<{ path: string; title: string; snippet: string; score: number; type: string }>;
  count: number;
}

export interface BatchDeleteResult {
  deleted_ids: string[];
  failed: Array<{ id: string; reason: string }>;
}

// ── Code-Graph ──

export interface CodeGraphDetail {
  code_graph_id: string;
  team_id: string;
  repo_name: string;
  repo_url: string;
  branch: string;
  /** External source ('gongfeng' etc.); null = public repo. */
  source_type: string | null;
  commit_hash: string | null;
  service_url: string | null;
  summary: string | null;
  status: 'pending' | 'processing' | 'ready' | 'failed';
  sync_error: string | null;
  version: string;
  owner_user_id: string | null;
  stats: { files: number; nodes: number; edges: number } | null;
  last_sync_at: string | null;
  created_at: string;
  updated_at: string;
}

export interface CodeGraphListResult {
  items: CodeGraphDetail[];
  total: number;
}

export interface CodeGraphSyncResult {
  code_graph_id: string;
  status: string;
}

export interface CodeGraphToolResult {
  text: string;
  isError: boolean;
}

// ── External sources (code platforms, e.g. Gongfeng) ──
// The source of truth for the source list and credential storage is KS; Panel only forwards, without copying config or holding plaintext.

export interface SourceProviderFormField {
  name: string;
  secret: boolean;
  required: boolean;
}

export interface SourceProviderMeta {
  id: string;
  /** Auth method type (bearer / basic / ...), based on which the frontend can show i18n-differentiated hints. */
  auth_method: "bearer" | "basic";
  /** Form field list, based on which the frontend dynamically renders credential inputs. */
  form_fields: readonly SourceProviderFormField[];
  token_doc_url?: string | null;
}

export interface SourceProviderList {
  items: SourceProviderMeta[];
}

// ── wiki external sources (iWiki etc.) ──
// Isomorphic with code sources: Panel only forwards; the source of truth is in KS.

/** wiki remote node (flat, including directory nodes). */
export interface WikiRemotePageRef {
  externalId: string;
  title: string;
  path: string;
  parentId?: string | null;
  /** true = directory, display only, not downloadable. */
  isDir?: boolean;
  version?: string;
  updatedAt?: string;
}

export interface WikiResolvedRoot {
  rootType: 'dir' | 'doc';
  rootId: string;
  displayName: string;
  estimatedCount?: number;
}

export interface WikiSourceListResult {
  root: WikiResolvedRoot;
  pages: WikiRemotePageRef[];
  /** Number of importable (non-directory) nodes. */
  importable: number;
}

export interface WikiSourceImportResult {
  imported: number;
  skippedDirs: number;
  failed: Array<{ id: string; error: string }>;
  warnings: string[];
}

/** Credential metadata (aligned with the KS-side CredentialStatus). Never contains the secret. */
export interface SourceCredentialStatus {
  resource_type: 'code-graph' | 'wiki';
  resource_id: string;
  provider_id: string;
  cred_kind: string;
  last_verified_at: string | null;
  updated_at: string;
}

// ── Port ──

export interface KnowledgeClientPort {
  // Wiki -- asset layer (create/list carry IdFields; get/ingest/delete are addressed by asset id only)
  /**
   * Create a wiki.
   * External sources (iWiki etc.) must pass **both** `sourceType` and `sourceUrl`:
   * source_type decides whether the detail page UI uses "Upload files" or "Pull from external", and the KS side returns 400 if either is missing.
   */
  wikiCreate(
    teamId: string,
    name: string,
    userId?: string,
    sourceUrl?: string,
    sourceType?: string,
  ): Promise<WikiDetail>;
  wikiGet(wikiId: string): Promise<WikiDetail>;
  /**
   * Trigger ingest (design 2026-09-21 §3.3).
   * opts.onBusy='replace' -> the KS side cancels the old task and queues the new one (returns queued);
   * default 'reject' -> returns 409 busy when there is an in-flight task.
   */
  wikiIngest(wikiId: string, opts?: { onBusy?: 'reject' | 'replace' }): Promise<WikiIngestResult>;
  wikiDelete(wikiIds: string[]): Promise<BatchDeleteResult>;
  wikiList(teamId: string, opts?: { status?: string; limit?: number; offset?: number }): Promise<WikiListResult>;
  wikiUpdateMeta(wikiId: string, patch: { name?: string; summary?: string | null }): Promise<WikiDetail>;

  // Wiki -- raw file layer (ls/read by asset id only; write/rm carry IdFields)
  wikiRawLs(wikiId: string): Promise<{ items: RawFileEntry[] }>;
  wikiRawRead(wikiId: string, filenames: string[]): Promise<{ items: WikiRawReadItem[] }>;
  wikiRawWrite(teamId: string, wikiId: string, files: WikiRawWriteFile[], userId?: string): Promise<{ items: WikiRawWriteItem[] }>;
  wikiRawRm(teamId: string, wikiId: string, filenames: string[], userId?: string): Promise<WikiRawRmResult>;

  // Wiki -- page file layer (ls/read by asset id only; write/rm carry IdFields)
  wikiPageLs(wikiId: string): Promise<{ items: PageEntry[] }>;
  wikiPageRead(wikiId: string, refs: string[]): Promise<{ items: WikiPageReadItem[] }>;
  wikiPageWrite(teamId: string, wikiId: string, pages: WikiPageWriteItem[], userId?: string): Promise<{ items: WikiPageWriteResultItem[] }>;
  wikiPageRm(teamId: string, wikiId: string, refs: string[], userId?: string): Promise<WikiPageRmResult>;

  // Wiki -- derived views (addressed by asset id only)
  wikiGraph(wikiId: string): Promise<WikiGraphData>;
  wikiSearch(wikiId: string, query: string, limit?: number, graph?: { hop?: number; decay?: number; minScore?: number }): Promise<WikiSearchResult>;

  // Code-Graph (create/list carry IdFields; get/sync/delete/queries are addressed by asset id only)
  codeGraphCreate(
    teamId: string,
    repoUrl: string,
    branch?: string,
    userId?: string,
    repoName?: string,
    opts?: { providerId?: string; secret?: string; username?: string },
  ): Promise<CodeGraphDetail>;
  codeGraphList(teamId: string, opts?: { status?: string; limit?: number; offset?: number }): Promise<CodeGraphListResult>;
  codeGraphGet(codeGraphId: string): Promise<CodeGraphDetail>;
  codeGraphSync(codeGraphId: string): Promise<CodeGraphSyncResult>;
  codeGraphDelete(codeGraphIds: string[]): Promise<BatchDeleteResult>;
  codeGraphUpdateMeta(codeGraphId: string, patch: { repo_name?: string; summary?: string | null }): Promise<CodeGraphDetail>;
  codeGraphQuery(codeGraphId: string, tool: string, params: Record<string, unknown>): Promise<CodeGraphToolResult>;

  // External sources (credentials attach to resources, located by resource_type + resource_id; the team gate is verified by KS)
  sourceProviderListCode(): Promise<SourceProviderList>;
  /** List of enabled wiki sources (data source for the frontend dropdown). */
  sourceProviderListWiki(): Promise<SourceProviderList>;

  // wiki external sources: list document tree / import (does not trigger ingest; credentials are injected by KS by wiki_id)
  wikiSourceList(params: {
    wikiId: string;
    sourceUrl: string;
    providerId: string;
    /** Traversal strategy; omitted -> use the provider default (tree for iWiki). */
    crawl?: { mode?: "tree" | "links"; maxDepth?: number };
    actor: { teamId: string; userId: string };
  }): Promise<WikiSourceListResult>;
  wikiSourceImport(params: {
    wikiId: string;
    sourceUrl: string;
    providerId: string;
    pageIds?: string[];
    actor: { teamId: string; userId: string };
  }): Promise<WikiSourceImportResult>;

  sourceCredentialStatus(
    resourceType: ResourceType,
    resourceId: string,
    actor: { teamId: string; userId: string },
  ): Promise<SourceCredentialStatus | null>;
  sourceCredentialPut(
    resourceType: ResourceType,
    resourceId: string,
    actor: { teamId: string; userId: string },
    input: { provider_id: string; cred_kind: string; secret: string; username?: string },
  ): Promise<SourceCredentialStatus>;
  sourceCredentialDelete(
    resourceType: ResourceType,
    resourceId: string,
    actor: { teamId: string; userId: string },
  ): Promise<{ deleted: boolean }>;
}

/** Resource type that external-source credentials attach to (aligned with the KS-side ResourceRef.type). */
export type ResourceType = 'code-graph' | 'wiki';

/** Compute the first 16 hex chars of the body's sha256 (for TopN GROUP BY dedup). Returns an empty string for an empty body. */
function bodyHash16(body: string): string {
  if (!body) return "";
  return createHash("sha256").update(body).digest("hex").slice(0, 16);
}


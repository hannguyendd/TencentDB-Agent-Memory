/**
 * SkillTriggerService — archive segment (§7.4).
 *
 * After the Handler's main flow decides "archiving is needed" it calls this module, completing in the following order "**write the archive first,
 * then register the task**":
 *   ① generate archive_key / task_id / archived_at_ms
 *   ② write the archive file (already exists = treated as success; if this step is slow or fails there is no orphan task)
 *   ③ grab the tasks-mutex → read `_tasks.json` → append the task → write back → enqueue in Redis within the same critical section
 *
 * Order change history:
 *   2026-07-20 — the original order was ①→②(write _tasks.json + enqueue inside tasksMutex)→③(write the archive),
 *   which once triggered in the test environment: writeArchive was slower than the worker BRPOP (due to CoS self-signed TLS + internal
 *   DNS jitter, a single put ~10s), the worker got in first, readArchive returned null, judged it a ghost, and silently dropped
 *   a real task. After changing to "archive first, then task": a slow/failed archive errors out in place on the handler side,
 *   the worker never sees a task without an archive, and on the happy path ghosts are not misjudged.
 *
 * Failure states under the new order:
 *   - writeArchive throws → the handler gets the exception, no residue in _tasks.json, no agent in Redis;
 *     the Client can retry the whole flow (archive is idempotent: the same archived_at_ms is skipped, not overwritten).
 *   - writeArchive succeeds → any of writeTasks / enqueueAgent failing inside the mutex → only leaves an
 *     "orphan archive" (a 4-to-tens-of-KB jsonl that the worker cannot see, cleaned up by the CoS lifecycle
 *     or later GC). This is much better than before: there is no longer any risk of losing tasks.
 */

import { randomUUID } from "node:crypto";

import type {
  AgentTuple,
  ISkillAgentTaskQueue,
} from "./agent-task-queue.js";
import type {
  BufferedMessages,
  SessionKey,
  SkillBufferStorage,
  SkillTaskEntry,
} from "./buffer-storage.js";
import { obsLogger } from "../../report/obs-logger.js";

export interface TriggerArchiveInput {
  session: SessionKey;
  bufferAtTrigger: BufferedMessages;
  /** Business-side task reference (passthrough field), optional. */
  taskRefId?: string;
  /**
   * Exclusive to direct-trigger (`/v3/skill/extract`): the main Agent's extraction hint,
   * landing in SkillTaskEntry.reason; the Worker passes it through to extractor.extract when consuming.
   * Not passed by the conversation/add path.
   */
  reason?: string;
  /**
   * Exclusive to direct-trigger: extractor LLM iteration cap, landing in SkillTaskEntry.max_iterations.
   * Not passed by the conversation/add path (uses the extractor-side default).
   */
  maxIterations?: number;
  /**
   * Extraction mode; passed as 'strict' only when the handler receives body.strict_mode:true, landing in
   * SkillTaskEntry.mode. When omitted the field is not written, always taking default (SKILL_REVIEW_PROMPT v2 lenient).
   */
  mode?: 'strict';
  /**
   * request_id generated by the upstream handler. When passed in, the trigger's internal segment obsLogger events
   * carry it, making it easy to filter the full handler + trigger + worker chain by req_id. Omission does not affect functionality.
   */
  perfRequestId?: string;
}

export interface TriggerArchiveResult {
  taskId: string;
  archivedAtMs: number;
  archiveKey: string;
}

export interface SkillTriggerServiceOptions {
  buffer: SkillBufferStorage;
  queue: ISkillAgentTaskQueue;
  /**
   * tasks-mutex lock TTL, default 10000ms. **The lock's own expiry time** — only a safety net so
   * it is released automatically after the lock-holding process crashes. The real critical section should be far smaller than this value (COS read-modify-write is usually <300ms).
   */
  tasksMutexLockTtlMs?: number;
  /**
   * Maximum wait time for contending the tasks-mutex, default 30000ms (30s).
   * When many sessions archive for the same agent concurrently (multiple sessions entering the critical section at once), queuing time accumulates,
   * and waitDeadline must be >> single critical-section duration × expected queue length.
   */
  tasksMutexWaitDeadlineMs?: number;
  /** Time source, for test injection. */
  now?: () => number;
}

export class SkillTriggerService {
  private readonly buffer: SkillBufferStorage;
  private readonly queue: ISkillAgentTaskQueue;
  private readonly tasksMutexLockTtlMs: number;
  private readonly tasksMutexWaitDeadlineMs: number;
  private readonly now: () => number;

  constructor(opts: SkillTriggerServiceOptions) {
    this.buffer = opts.buffer;
    this.queue = opts.queue;
    this.tasksMutexLockTtlMs = opts.tasksMutexLockTtlMs ?? 10_000;
    this.tasksMutexWaitDeadlineMs = opts.tasksMutexWaitDeadlineMs ?? 30_000;
    this.now = opts.now ?? (() => Date.now());
  }

  /**
   * Trigger one archive. Performs §7.4 ①→②→③→④.
   * On failure it throws, letting the Handler convert it into a 500 for the Client to retry.
   */
  async archive(input: TriggerArchiveInput): Promise<TriggerArchiveResult> {
    const { session, bufferAtTrigger, taskRefId } = input;

    // ① generate identifiers
    const archivedAtMs = this.now();
    const archiveKey = this.buffer.archiveKey(session, archivedAtMs);
    // The prefix `skill-extract-task-` is an internal anchor (clearly distinguished from the business-side task_id).
    // One archive = one SkillTaskEntry.task_id; the handler-side `[skill-perf] phase=trigger.enqueueAgent
    // task_id=…` and the worker-side `[skill-perf] kind=worker phase=consume.*` share the same
    // value, so one grep pulls the full handler + worker two-segment timing. Old data with the `task-` prefix is
    // consumed by the worker naturally, with no migration risk (filter compares the task_id value for equality and does not parse the prefix).
    const taskId = `skill-extract-task-${randomUUID().slice(0, 8)}`;
    const agent: AgentTuple = {
      // 2026-07-30 instance_id is put into the tuple; after coming out of the queue the worker pool routes by it
      // to the resources of the corresponding instance. If not given or empty it throws directly.
      instance_id: session.instance_id,
      space_id: session.space_id,
      user_id: session.user_id,
      team_id: session.team_id,
      agent_id: session.agent_id,
    };

    const entry: SkillTaskEntry = {
      task_id: taskId,
      session_id: session.session_id,
      user_id: session.user_id,
      team_id: session.team_id,
      agent_id: session.agent_id,
      space_id: session.space_id,
      task_ref_id: taskRefId,
      archive_key: archiveKey,
      archived_at_ms: archivedAtMs,
      enqueued_at_ms: archivedAtMs,
      reason: input.reason,
      max_iterations: input.maxIterations,
      // mode is written only for strict; default undefined keeps old task deserialization + the old Worker
      // consumption path consistent with history (extract() without mode → SKILL_REVIEW_PROMPT).
      ...(input.mode ? { mode: input.mode } : {}),
    };

    // [obs] the archive segment's five key IOs: writeArchive / mutex acquire / readTasks /
    // writeTasks / enqueueAgent. In a historical incident a writeArchive taking 10s brought down the
    // worker side's emptiness check; here each segment is a structured event, correlated by req_id / task_id fields.
    // obsLogger has internal try/catch + backend degradation; no extra defense is needed.
    const rid = input.perfRequestId;
    const instanceId = session.instance_id;

    // ② write the archive first (already exists is treated as success)
    //
    // Rationale for the order here: when the worker-side readArchive gets null it judges a ghost and directly deletes
    // the corresponding task; if the archive segment came after the task segment, any CoS jitter (slow self-signed TLS handshake,
    // internal DNS re-resolution, etc.) would stretch out a window where "the task is registered but the archive is not yet written",
    // and a worker BRPOP landing in this window would drop a real task as a ghost (2026-07-20 production
    // incident: writeArchive took 10s, two cores split the work, and the other one dropped the task
    // at 5s). After changing to archive first and then task: neither a thrown nor a slow writeArchive
    // can cause an orphan task; the worker only ever sees a task once the archive already exists.
    //
    // Failure state: writeArchive throws → throw directly to the handler, no residue.
    const t0Arch = Date.now();
    await this.buffer.writeArchive(session, archivedAtMs, bufferAtTrigger);
    obsLogger.info("skill.trigger.write_archive", {
      req_id: rid, task_id: taskId, instance_id: instanceId,
      dur_ms: Date.now() - t0Arch,
      archive_key: archiveKey,
    });

    // ③ grab the mutex → CAS-append the task to the queue tail → enqueue within the same lock
    //
    // Key guarantee (root cause of phantom tasks): writeTasks and enqueueAgent must complete within the same
    // tasks-mutex critical section, otherwise a race window appears with the Worker side's "emptiness check → removeAgent":
    // before the Worker calls removeAgent outside the mutex, this function's
    // enqueueAgent may already skip the LPUSH because the old agent still remains in the Set (SADD returns 0),
    // leaving a new task landed in _tasks.json but the Redis queue with
    // no record of that agent — the task is stuck forever, and no later mechanism re-triggers it.
    // Pulling enqueueAgent into the same lock, together with the Worker-side fix (see extract-worker.ts),
    // guarantees "write task + enqueue" and "emptiness check + dequeue" are mutually exclusive and never interleave.
    const t0MutexEntry = Date.now();
    await this.queue.withTasksMutex(
      agent,
      { lockTtlMs: this.tasksMutexLockTtlMs, waitDeadlineMs: this.tasksMutexWaitDeadlineMs },
      async () => {
        const mutexAcquiredAt = Date.now();
        obsLogger.info("skill.trigger.mutex_acquire", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: mutexAcquiredAt - t0MutexEntry,
        });

        const t0Read = Date.now();
        const doc = await this.buffer.readTasks(agent);
        obsLogger.info("skill.trigger.read_tasks", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Read,
          existing_tasks: doc.tasks.length,
        });

        doc.tasks.push(entry);
        doc.updated_at_ms = archivedAtMs;

        const t0Write = Date.now();
        await this.buffer.writeTasks(agent, doc);
        obsLogger.info("skill.trigger.write_tasks", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Write,
          total_tasks: doc.tasks.length,
        });

        const t0Enq = Date.now();
        const enqueued = await this.queue.enqueueAgent(agent);
        obsLogger.info("skill.trigger.enqueue_agent", {
          req_id: rid, task_id: taskId, instance_id: instanceId,
          dur_ms: Date.now() - t0Enq,
          added: enqueued,
        });
      },
    );
    obsLogger.info("skill.trigger.mutex_total", {
      req_id: rid, task_id: taskId, instance_id: instanceId,
      dur_ms: Date.now() - t0MutexEntry,
    });

    return { taskId, archivedAtMs, archiveKey };
  }
}

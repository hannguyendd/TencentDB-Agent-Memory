export class PanelAuthError extends Error {
  constructor(readonly code: string, message: string, readonly status = 401) {
    super(message);
    this.name = 'PanelAuthError';
  }
}

export interface AuthMethodView {
  id: string;
  type: 'user_key' | 'woa';
  display_name: string;
  enabled: boolean;
}

export interface IdpLoginResult {
  session: IdpSession;
  identity: ExternalIdentity;
  /** Newly created account's user_key, shown once (for the user to copy into the client connecting to the proxy); empty when an already-bound user logs in again. */
  userKeyDisplay?: string;
  /** true = the key was auto-generated by the kernel (must be shown once); false = user-defined (no need to echo back). */
  userKeyAutogenerated?: boolean;
}

export interface PendingWoaLogin {
  token: string;
  instanceId: string;
  identity: ExternalIdentity;
  expiresAt: number;
}

/**
 * Format constraints for a user-supplied user_key.
 *
 * This endpoint allows "create the account if the key does not exist" (register on first login) and is a **credential-free** public entry point,
 * so even without a feature switch it must block three kinds of input, otherwise it is effectively an open hole for arbitrary DB writes:
 * - Too short (including empty): anyone could mass-create accounts by typing a few characters;
 * - Too long: very long strings would blow up storage / logs;
 * - Containing control characters / whitespace: newlines pollute logs (CRLF injection), and spaces create "two keys that look identical".
 *
 * Only length and charset are constrained; the `sk-mem-` prefix is not checked -- a user's own key may come from any system
 * (e.g. keys issued by CodeBuddy), and forcing a prefix would directly defeat the goal of "supporting user-held keys".
 */
const USER_KEY_MIN_LENGTH = 8;
const USER_KEY_MAX_LENGTH = 256;
// Use the Unicode property class \p{Cc} to express "control characters" rather than writing escapes like \x00-\x1f
// in the regex (which would trigger no-control-regex); it also covers more (including U+0080-U+009F).
const USER_KEY_PATTERN = /^[^\s\p{Cc}]+$/u;

function assertUsableUserKey(key: string): string {
  const trimmed = key.trim();
  if (!trimmed) {
    throw new PanelAuthError('INVALID_USER_KEY', 'user_key must not be empty', 400);
  }
  if (trimmed.length < USER_KEY_MIN_LENGTH) {
    throw new PanelAuthError(
      'INVALID_USER_KEY',
      `user_key must be at least ${USER_KEY_MIN_LENGTH} characters`,
      400,
    );
  }
  if (trimmed.length > USER_KEY_MAX_LENGTH) {
    throw new PanelAuthError(
      'INVALID_USER_KEY',
      `user_key must be at most ${USER_KEY_MAX_LENGTH} characters`,
      400,
    );
  }
  if (!USER_KEY_PATTERN.test(trimmed)) {
    throw new PanelAuthError(
      'INVALID_USER_KEY',
      'user_key must not contain whitespace or control characters',
      400,
    );
  }
  return trimmed;
}

interface PendingWoaPayload {
  version: 1;
  instanceId: string;
  identity: Omit<ExternalIdentity, 'claims'>;
  expiresAt: number;
  nonce: string;
}

interface PanelAuthDependencies {
  config: PanelAuthConfig;
  instances: InstanceRegistry;
  metaKernel: MetaKernelPort;
  logger: Logger;
}

export class PanelAuthService {
  private readonly config: PanelAuthConfig;
  private readonly instances: InstanceRegistry;
  private readonly metaKernel: MetaKernelPort;
  private readonly logger: Logger;
  private readonly sessions: MemorySessionStore;
  private readonly identities: FileIdentityStore;
  private readonly providers = new AuthProviderRegistry();
  private readonly consumedPendingWoa = new Set<string>();

  constructor(dependencies: PanelAuthDependencies) {
    const { config, instances, metaKernel, logger } = dependencies;
    this.config = config;
    this.instances = instances;
    this.metaKernel = metaKernel;
    this.logger = logger;
    if (!config.userKeyEnabled && !config.idpEnabled) {
      throw new Error('at least one Panel authentication method must be enabled');
    }
    // sessionSecret is generated internally by the config layer and persisted to a 0600 file (external configuration is not accepted);
    // empty means generation/reading failed -- this is an internal fault, not a missing config, and the error is worded accordingly.
    if (config.idpEnabled && !config.sessionSecret) {
      throw new Error('session secret is unavailable: internal generation or persistence failed');
    }
    this.sessions = new MemorySessionStore(config.sessionTtlSeconds);
    this.identities = new FileIdentityStore(config.identityStorePath);
    // Providers all go through the registry: the historical private `this.woa` field is removed.
    // When a second Provider (OAuth2/OIDC) is added, just add `providers.register(...)` here;
    // there is no need to add another same-named field on the Service.
    if (config.idpEnabled && config.woa.enabled) {
      this.providers.register(new WoaProvider({
        enabled: config.woa.enabled,
        appToken: config.woa.appToken,
        safeMode: config.woa.safeMode,
        requireSignature: config.woa.requireSignature,
        appUrl: config.woa.appUrl,
        loginUrl: config.woa.loginUrl,
        logoutUrl: config.woa.logoutUrl,
        paasId: config.woa.paasId,
        authProvider: config.woa.authProvider,
      }));
    }
  }

  listMethods(): AuthMethodView[] {
    const methods: AuthMethodView[] = [];
    if (this.config.userKeyEnabled) {
      methods.push({ id: 'user_key', type: 'user_key', display_name: 'user_key', enabled: true });
    }
    // The type field temporarily keeps the literal 'woa' (frontend LoginGate.tsx / auth.ts / i18n already assert on it);
    // generalizing the naming is a PR-3 route/contract extension task, unrelated to this PR.
    const woa = this.providers.get('woa');
    if (woa) {
      methods.push({ id: 'woa', type: 'woa', display_name: woa.displayName, enabled: true });
    }
    return methods;
  }

  /**
   * Lets the ingress / callback routes enumerate live header-injected Providers (e.g. WOA).
   *
   * Returns only **registered** Providers; an empty array when not enabled -- routes use this to decide whether to handle requests carrying
   * `ingressHeaderName`, avoiding "WOA is off yet still hijacked by the WOA flow".
   */
  listHeaderInjectedProviders(): HeaderInjectedProvider[] {
    return this.providers.listByKind('header-injected');
  }

  buildWoaLoginUrl(instanceId: string, returnTo: string): string {
    const provider = this.requireWoa();
    this.requireInstance(instanceId);
    const callback = this.buildCallbackUrl(instanceId, returnTo);
    return provider.buildLoginUrl(callback);
  }

  buildWoaLogoutUrl(returnTo: string): string {
    return this.requireWoa().buildLogoutUrl(this.safeReturnTo(returnTo));
  }

  async completeWoaLogin(
    ...[instanceId, headers, _returnTo, requestId]: [
      string,
      Record<string, string | undefined>,
      string,
      (string | undefined)?,
    ]
  ): Promise<IdpLoginResult> {
    const provider = this.requireWoa();
    const identity = await provider.authenticateFromHeaders(headers);
    if (!identity) throw new PanelAuthError('WOA_IDENTITY_INVALID', 'WOA identity headers are invalid', 401);
    const resolved = await this.resolveIdentity(instanceId, identity, requestId);
    const session = this.sessions.create({
      instanceId,
      coreUserId: resolved.coreUserId,
      userKey: resolved.userKey,
      providerId: identity.providerId,
      externalSubject: identity.subject,
      displayName: identity.displayName ?? identity.loginName,
      user: resolved.user,
    });
    return { session, identity };
  }

  async createPendingWoaLogin(input: {
    instanceId: string;
    headers: Record<string, string | undefined>;
  }): Promise<PendingWoaLogin> {
    const identity = await this.requireWoa().authenticateFromHeaders(input.headers);
    if (!identity) throw new PanelAuthError('WOA_IDENTITY_INVALID', 'WOA identity headers are invalid', 401);
    this.requireInstance(input.instanceId);
    const expiresAt = Date.now() + 5 * 60 * 1000;
    const payload: PendingWoaPayload = {
      version: 1,
      instanceId: input.instanceId,
      identity: {
        providerId: identity.providerId,
        subject: identity.subject,
        loginName: identity.loginName,
        displayName: identity.displayName,
        email: identity.email,
        staffId: identity.staffId,
        departmentId: identity.departmentId,
        departmentName: identity.departmentName,
      },
      expiresAt,
      nonce: randomUUID(),
    };
    const token = encryptSecret(JSON.stringify(payload), this.config.sessionSecret);
    return { token, instanceId: input.instanceId, identity, expiresAt };
  }

  getPendingWoaLogin(token: string | undefined): PendingWoaLogin | null {
    // When WOA is off it is "completely transparent": even if the browser retains a stale pending cookie, do not respond to it.
    // Otherwise /auth/session would return pending=true, the frontend would render the WOA confirmation page -> a "go to WOA" button exists
    // -> after the user clicks, loginWoa() jumps the whole page to WOA_LOGIN_URL, breaking "with WOA off it should behave as before the feature".
    if (!this.providers.get('woa')) return null;
    if (!token || this.consumedPendingWoa.has(token)) return null;
    try {
      const parsed = JSON.parse(decryptSecret(token, this.config.sessionSecret)) as unknown;
      if (!parsed || typeof parsed !== 'object') return null;
      const payload = parsed as Partial<PendingWoaPayload>;
      const identity = payload.identity;
      if (
        payload.version !== 1 ||
        typeof payload.instanceId !== 'string' ||
        typeof payload.expiresAt !== 'number' ||
        !identity ||
        typeof identity !== 'object' ||
        typeof identity.providerId !== 'string' ||
        typeof identity.subject !== 'string' ||
        typeof identity.loginName !== 'string'
      ) return null;
      if (payload.expiresAt <= Date.now()) return null;
      return {
        token,
        instanceId: payload.instanceId,
        identity: { ...identity, claims: {} } as ExternalIdentity,
        expiresAt: payload.expiresAt,
      };
    } catch {
      return null;
    }
  }

  /**
   * Get the unique user id under the external auth system (corresponds to core's meta_users.external_id).
   *
   * Prefer the employee number (staffId) -- it is a stable, unchanging identifier;
   * fall back to subject only when staffId is missing (the provider side guarantees subject = staffId || loginName).
   * loginName is not preferred: a login name may change through renaming/normalization, which would invalidate the binding.
   */
  private externalAuthIdOf(identity: {
    staffId?: string;
    subject: string;
    loginName: string;
  }): string {
    const staffId = identity.staffId?.trim();
    if (staffId) return staffId;
    return identity.subject.trim() || identity.loginName.trim();
  }

  /**
   * Preview: whether the user-supplied user_key already exists in core.
   *
   * The key anti-mis-binding step of the first external-auth login -- let the user see clearly "whose key this is" first,
   * then confirm whether to bind it or create a new account, rather than silently deciding for them:
   * - key exists -> return that account's info (user_id/username); after the user confirms, **bind** it, keeping all old data intact;
   * - key does not exist -> after the user confirms, **create** a new account with this key.
   */
  async previewPendingWoaLogin(input: {
    token: string;
    userKey: string;
    requestId?: string;
  }): Promise<{
    exists: boolean;
    user_id?: string;
    username?: string;
    display_name?: string;
    user_type?: string;
  }> {
    const pending = this.getPendingWoaLogin(input.token);
    if (!pending) throw new PanelAuthError('WOA_LOGIN_EXPIRED', 'WOA login confirmation expired', 401);

    const entry = this.requireInstance(pending.instanceId);
    const context = this.context(entry, entry.api_key, input.requestId);
    const key = input.userKey.trim();
    if (!key) {
      throw new PanelAuthError('INVALID_USER_KEY', 'user_key must not be empty', 400);
    }

    const verified = await this.metaKernel.invoke('auth/verify', { user_key: key }, context);
    // Check validity first and only then hand off to readVerifiedUser: the latter throws on an invalid key,
    // while "key does not exist" is a normal branch here and should not be masked by catch (that would swallow network/parse errors too).
    const data = verified?.data as { valid?: boolean } | null;
    if (verified?.code !== 0 || data?.valid !== true) return { exists: false };

    const { user } = this.readVerifiedUser(verified);
    return {
      exists: true,
      user_id: user.user_id,
      username: user.username,
      display_name: user.display_name,
      user_type: user.user_type,
    };
  }

  async completePendingWoaLogin(input: {
    token: string;
    username?: string;
    userKey?: string;
    customUserKey?: string;
    requestId?: string;
  }): Promise<IdpLoginResult> {
    const pending = this.getPendingWoaLogin(input.token);
    if (!pending) throw new PanelAuthError('WOA_LOGIN_EXPIRED', 'WOA login confirmation expired', 401);

    // First external-auth login: the user must provide a user_key --
    // - already exists in the system -> bind to that existing account (old data fully retained);
    // - does not exist -> create a new account with this key.
    // The user should call previewPendingWoaLogin before submitting to see whose key this is, then confirm.
    const userKey = input.userKey?.trim() || input.customUserKey?.trim();
    if (!userKey) {
      throw new PanelAuthError('INVALID_USER_KEY', 'user_key is required', 400);
    }
    const resolved = await this.provisionIdentity({
      instanceId: pending.instanceId,
      identity: pending.identity,
      requestId: input.requestId,
      username: input.username?.trim() || undefined,
      customUserKey: userKey,
    });
    this.consumedPendingWoa.add(input.token);
    const session = this.sessions.create({
      instanceId: pending.instanceId,
      coreUserId: resolved.coreUserId,
      userKey: resolved.userKey,
      providerId: pending.identity.providerId,
      externalSubject: pending.identity.subject,
      displayName: pending.identity.displayName ?? pending.identity.loginName,
      user: resolved.user,
    });
    return {
      session,
      identity: pending.identity,
      // The key is provided by the user (whether binding an existing account or creating a new one), so no need to echo it back.
      userKeyDisplay: undefined,
      userKeyAutogenerated: false,
    };
  }

  /**
   * Preview: whether the user-supplied user_key already has a corresponding account in the system.
   *
   * Same shape as previewPendingWoaLogin, serving the "support user-held keys" login:
   * - key exists -> return account info (user_id/username); after the user confirms, **log in** to it;
   * - key does not exist -> after the user confirms, **create** a new account with this key and log in.
   *
   * The two-step confirmation prevents mis-binding: let the user see "whose key this is" first, then decide to log in or create,
   * instead of silently creating an account on their behalf in the login request.
   */
  async previewUserKeyLogin(input: {
    instanceId: string;
    userKey: string;
    requestId?: string;
  }): Promise<{
    exists: boolean;
    user_id?: string;
    username?: string;
    display_name?: string;
    user_type?: string;
  }> {
    const key = assertUsableUserKey(input.userKey);
    const entry = this.requireInstance(input.instanceId);
    // The preview is a "read-only probe"; use the instance admin key as the gateway Bearer (no user credentials available);
    // auth/verify decides only by the user_key in the body and does not read the caller's identity.
    const context = this.context(entry, entry.api_key, input.requestId);
    const verified = await this.metaKernel.invoke('auth/verify', { user_key: key }, context);
    const data = verified?.data as { valid?: boolean } | null;
    if (verified?.code !== 0 || data?.valid !== true) return { exists: false };

    const { user } = this.readVerifiedUser(verified);
    return {
      exists: true,
      user_id: user.user_id,
      username: user.username,
      display_name: user.display_name,
      user_type: user.user_type,
    };
  }

  /**
   * Log in with the user-supplied user_key; create the account when the key does not exist (register on first login).
   *
   * The caller must first have the user confirm ownership via previewUserKeyLogin (two-step confirmation);
   * this method only performs the action.
   */
  async loginWithUserKey(input: {
    instanceId: string;
    userKey: string;
    username?: string;
    requestId?: string;
  }): Promise<{ user_id: string; user: SessionUser; created: boolean }> {
    const key = assertUsableUserKey(input.userKey);
    const entry = this.requireInstance(input.instanceId);
    const context = this.context(entry, entry.api_key, input.requestId);

    // Already exists -> log in directly, no account creation.
    const probe = await this.metaKernel.invoke('auth/verify', { user_key: key }, context);
    const probeData = probe?.data as { valid?: boolean } | null;
    if (probe?.code === 0 && probeData?.valid === true) {
      const { user_id, user } = this.readVerifiedUser(probe);
      return { user_id, user, created: false };
    }

    // Does not exist -> create the account with this key.
    // user/create-with-key is an admin-level endpoint (core side assertCanManageUsers),
    // called with the instance api_key as user_key (see section 12.3: single admin credential source).
    const username = input.username?.trim() || this.usernameFromKey(key);
    const created = await this.metaKernel.invoke(
      'user/create-with-key',
      { username, user_key: key },
      context,
    );
    if (!created || created.code !== 0) {
      // 409 duplicate_user_key: under concurrency someone else created an account with the same key first; fall back to logging in.
      if (created?.code === 409) {
        const { user_id, user } = await this.verifyCoreUser(input.instanceId, key, input.requestId);
        return { user_id, user, created: false };
      }
      throw new PanelAuthError(
        'USER_CREATE_FAILED',
        created?.message || 'failed to create user with the provided key',
        502,
      );
    }
    const { user_id, user } = await this.verifyCoreUser(input.instanceId, key, input.requestId);
    return { user_id, user, created: true };
  }

  /** Default username on account creation: take a readable fragment of the key so a long secret is not used directly as the display name. */
  private usernameFromKey(key: string): string {
    const tail = key.length > 12 ? key.slice(-12) : key;
    return `user-${tail}`;
  }

  /**
   * Abandon the current pending WOA login (the user chose to log in with user_key instead).
   *
   * This only marks the pending token as consumed (it can no longer complete account creation); the real "stop bouncing me back to the WOA confirmation page"
   * is guaranteed by the dismissed cookie issued by the route layer (the gateway injects identity headers on every request, so an in-memory mark alone would
   * be lost after a process restart, and a page refresh would immediately recreate the pending).
   */
  dismissPendingWoaLogin(token: string | undefined): void {
    if (token) this.consumedPendingWoa.add(token);
  }

  async bindWoaIdentity(
    ...[instanceId, userKey, headers, requestId]: [
      string,
      string,
      Record<string, string | undefined>,
      (string | undefined)?,
    ]
  ): Promise<{ coreUserId: string; identity: ExternalIdentity }> {
    const provider = this.requireWoa();
    const identity = await provider.authenticateFromHeaders(headers);
    if (!identity) throw new PanelAuthError('WOA_IDENTITY_INVALID', 'WOA identity headers are invalid', 401);
    const entry = this.requireInstance(instanceId);
    const context = this.context(entry, userKey, requestId);
    const verified = await this.metaKernel.invoke('auth/verify', { user_key: userKey }, context);
    const user = this.readVerifiedUser(verified);
    this.saveIdentityBinding(instanceId, identity, user.user_id, userKey);
    return { coreUserId: user.user_id, identity };
  }

  resolveSession(instanceId: string, cookieToken: string | undefined): IdpSession | null {
    const session = this.sessions.get(cookieToken);
    return session?.instanceId === instanceId ? session : null;
  }

  getSession(cookieToken: string | undefined): IdpSession | null {
    return this.sessions.get(cookieToken);
  }

  destroySession(cookieToken: string | undefined): void {
    this.sessions.destroy(cookieToken);
  }

  async resolveIdentity(
    instanceId: string,
    identity: ExternalIdentity,
    requestId?: string,
  ): Promise<{ coreUserId: string; userKey: string; user: SessionUser }> {
    const existing = this.identities.find(instanceId, identity.providerId, identity.subject);
    if (existing) {
      let userKey: string;
      try {
        userKey = decryptSecret(existing.encryptedUserKey, this.config.sessionSecret);
      } catch {
        throw new PanelAuthError('IDENTITY_BINDING_CORRUPT', 'stored IdP identity binding cannot be decrypted', 500);
      }
      const verified = await this.verifyCoreUser(instanceId, userKey, requestId);
      return {
        coreUserId: existing.coreUserId,
        userKey,
        user: verified.user,
      };
    }

    // Fallback when the local binding file is missing (volume lost / session-secret rotated / cross-deployment):
    // look up Core directly by external identity (auth_provider, external_id); a hit is treated as an existing-user login,
    // without forcing the user to re-enter a key for first-time binding. This path is driven by WOA=on itself (only reached when the Panel has WOA
    // enabled), and introduces no default-off switch.
    const resolvedFromCore = await this.resolveIdentityFromCore(instanceId, identity, requestId);
    if (resolvedFromCore) return resolvedFromCore;

    throw new PanelAuthError(
      'IDENTITY_NOT_BOUND',
      'WOA identity is authenticated but has not been bound to a Memory user',
      403,
    );
  }

  /**
   * When the local binding is missing, look up Core by external identity to complete login (no local binding file needed).
   *
   * Flow:
   *   (1) user/find-by-external looks up by (auth_provider, external_id) -> get core user_id;
   *      no hit -> return null (the upper layer treats it as a "true first login").
   *   (2) user-key/create issues a new user_key for the account using the instance api_key
   *      (Core does not return the plaintext of an existing key, so a new one must be issued; later meta requests use it as x-tdai-user-key).
   *   (3) Write back the local binding cache to speed up the next login and reduce Core round trips.
   *
   * Only the instance api_key (system_admin) is used throughout, consistent with the "single admin credential source".
   */
  private async resolveIdentityFromCore(
    instanceId: string,
    identity: ExternalIdentity,
    requestId?: string,
  ): Promise<{ coreUserId: string; userKey: string; user: SessionUser } | null> {
    const externalId = this.externalAuthIdOf(identity);
    if (!externalId) return null;
    const entry = this.requireInstance(instanceId);
    const context = this.context(entry, entry.api_key, requestId);

    // Look up two kinds of accounts by external_id; their auth_provider differs:
    //   (1) Accounts newly created on first WOA login -> provisionIdentity sets auth_provider=woa on creation;
    //   (2) Existing accounts bound to WOA -> Core bindExternalIdentity deliberately "writes only external_id,
    //      without changing auth_provider", keeping the provider from creation time (usually local).
    // A single provider would miss the other kind, so look up in order woa -> default (local).
    // No false hits: an account with no bound external identity falls back to a usr-xxx external_id, which differs from numeric employee numbers.
    const coreUserId = await this.lookupCoreUserByExternal(externalId, context);
    if (!coreUserId) return null;

    // Issue a new user_key for the found account (Core does not hand out plaintext of existing keys).
    const issued = await this.metaKernel.invoke(
      'user-key/create',
      { user_id: coreUserId, name: 'woa-login' },
      context,
    );
    if (issued?.code !== 0 || !issued.data || typeof issued.data !== 'object') {
      // Active-key limit reached, etc.: do not hard-fail and get stuck; return null so the upper layer goes through first-login pending,
      // and the user completes binding on the confirmation page with their own user_key (that key will be reused, not newly issued).
      this.logger.warn('WOA core-fallback key issue failed, degrading to pending', {
        instanceId, coreUserId, code: issued?.code, message: issued?.message,
      });
      return null;
    }
    const userKey = (issued.data as { key_value?: unknown }).key_value;
    if (typeof userKey !== 'string' || !userKey) {
      throw new PanelAuthError('WOA_KEY_ISSUE_INVALID', 'Core returned an invalid user_key', 502);
    }

    const verified = await this.verifyCoreUser(instanceId, userKey, requestId);
    // Write back the local binding cache: the next login hits the local path directly without calling Core again.
    // A write-back failure (read-only volume / disk full) does not block this login -- the next one can still fall back to the Core lookup.
    try {
      this.saveIdentityBinding(instanceId, identity, coreUserId, userKey);
    } catch (err) {
      this.logger.warn('WOA identity binding cache write failed (non-fatal)', {
        instanceId, coreUserId, err: err instanceof Error ? err.message : String(err),
      });
    }
    return { coreUserId, userKey, user: verified.user };
  }

  /**
   * Look up a Core account by external_id, covering accounts of two different auth_providers.
   *
   * Tries in order:
   *   (1) auth_provider=woa -- accounts newly created on first WOA login;
   *   (2) auth_provider omitted (Core falls back to local) -- existing accounts bound to WOA.
   * Return user_id on the first hit; return null if neither hits (the upper layer handles it as a first login).
   */
  private async lookupCoreUserByExternal(
    externalId: string,
    context: ReturnType<PanelAuthService['context']>,
  ): Promise<string | null> {
    // Currently only the WOA Provider is mounted, so using requireWoa().authProviderDomain is equivalent to
    // config.woa.authProvider; when a second Provider is added, this domain should become
    // "the domain of the Provider that the identity being handled belongs to" (pass identity.providerId down the call chain).
    const providers: Array<string | undefined> = [this.requireWoa().authProviderDomain, undefined];
    const tried = new Set<string>();
    for (const provider of providers) {
      const dedupKey = provider ?? '__default__';
      if (tried.has(dedupKey)) continue;
      tried.add(dedupKey);
      const body: Record<string, string> = { external_id: externalId };
      if (provider) body.auth_provider = provider;
      const found = await this.metaKernel.invoke('user/find-by-external', body, context);
      if (found?.code !== 0) {
        this.logger.warn('WOA core-fallback find-by-external errored', {
          provider: dedupKey, code: found?.code, message: found?.message,
        });
        continue;
      }
      const data = found.data;
      if (!data || typeof data !== 'object') continue;
      const coreUserId = (data as { user_id?: unknown }).user_id;
      if (typeof coreUserId === 'string' && coreUserId) return coreUserId;
    }
    return null;
  }

  /**
   * Establish the external-auth association: bind the external unique id (employee number) to core's user (written to a separate association table).
   *
   * Both existing-account binding and new-account creation go through here, keeping the association semantics of the two paths consistent.
   * A failed association must fail the whole flow -- otherwise the next login would be misjudged as "first time" and ask for the key again.
   */
  private async bindExternalAuth(
    coreUserId: string,
    identity: ExternalIdentity,
    context: ReturnType<PanelAuthService['context']>,
  ): Promise<void> {
    const externalAuthId = this.externalAuthIdOf(identity);
    if (!externalAuthId) {
      throw new PanelAuthError(
        'EXTERNAL_AUTH_ID_MISSING',
        'external identity does not carry a usable user id (staffId/subject)',
        400,
      );
    }
    // auth_provider / display_name are persisted together, keeping the same external domain as the account-creation path,
    // avoiding 401s from "binding writes domain A while auth looks up domain B"; the display name makes the member list show the Chinese name
    // rather than the login name (core only fills it in when the target account's display_name is empty, never overwriting).
    await this.metaKernel.invoke('user/bind-external', {
      user_id: coreUserId,
      external_id: externalAuthId,
      auth_provider: this.requireWoa().authProviderDomain,
      display_name: identity.displayName?.trim() || undefined,
    }, context);
  }

  private async provisionIdentity(input: {
    instanceId: string;
    identity: ExternalIdentity;
    requestId?: string;
    username?: string;
    customUserKey?: string;
  }): Promise<{ coreUserId: string; userKey: string; user: SessionUser }> {
    const { instanceId, identity, requestId, customUserKey } = input;
    const entry = this.requireInstance(instanceId);
    // Idempotency fallback: under concurrency/duplicate submission we may re-enter before the previous account creation is written to disk;
    // previously the unique constraint "user_id = login name" blocked duplicate creation; after switching to kernel-generated usr-xxx
    // that constraint is gone, so we must explicitly check whether a binding already exists before creating the account.
    const alreadyBound = this.identities.find(instanceId, identity.providerId, identity.subject);
    if (alreadyBound) return this.resolveIdentity(instanceId, identity, requestId);
    // WOA account creation: username defaults to the WOA login name (editable on the confirmation page), decoupled from user_id.
    // user_id does **not** use the login name; it is left to the kernel to generate usr-xxx with the same logic as the admin "create and bind account",
    // avoiding writing an external identity into the primary key (renames/duplicates/cross-IdP conflicts would directly break ownership).
    const username = (input.username || identity.loginName || identity.subject).trim();
    if (!/^[A-Za-z0-9_-]+$/.test(username)) {
      throw new PanelAuthError('INVALID_USERNAME', 'username must contain only letters, numbers, underscores, or hyphens', 400);
    }
    if (customUserKey !== undefined && customUserKey.length < 8) {
      throw new PanelAuthError('INVALID_CUSTOM_USER_KEY', 'custom user_key is too short', 400);
    }
    // Account creation requires system_admin: user/create(-with-key)'s assertCanManageUsers no longer has
    // a "no user-key allowlist" branch, so an admin user_key must be supplied.
    // Single credential source (see section 12.3): always use the instance api_key; no separate admin key config item.
    // Deployment prerequisite: the instance api_key must resolve to system_admin on the core side, otherwise account creation returns 401.
    const context = this.context(entry, entry.api_key, requestId);

    // Existing-account onboarding: if the key the user gave already exists in the system, bind the external identity to **that existing account**
    // instead of creating a new one -- so old data (memories/teams/skills) is retained as-is.
    if (customUserKey) {
      // verifyCoreUser throws when the key is invalid/nonexistent; here we need "return null if not found" semantics,
      // so call auth/verify separately and decide ourselves, without going through verifyCoreUser.
      const envelope = await this.metaKernel.invoke(
        'auth/verify',
        { user_key: customUserKey },
        this.context(entry, customUserKey, requestId),
      );
      const data = envelope?.data as { valid?: boolean } | null;
      const existingId = envelope?.code === 0 && data?.valid === true
        ? this.readVerifiedUser(envelope).user_id
        : undefined;
      if (existingId) {
        // Idempotent: it may already be bound under concurrency/retry; bindExternalIdToUser handles this internally.
        await this.bindExternalAuth(existingId, identity, context);
        const verified = await this.verifyCoreUser(instanceId, customUserKey, requestId);
        return { coreUserId: verified.user_id, userKey: customUserKey, user: verified.user };
      }
    }

    // Consistent with admin "create and bind account": do not pass user_id; the kernel generates usr-xxx;
    // default user/create has the kernel generate the key; an explicit custom key goes through user/create-with-key.
    //
    // Account creation carries the external identity triple (external_id / auth_provider / display_name) right away:
    // it uses the same external domain as bindExternalAuth, ensuring the account can be found by find-by-external
    // immediately after creation. Calling bind-external afterwards would also fill it in, but costs an extra round trip and a mid-way failure would leave an
    // "created but unbound" orphan account.
    const identityFields = {
      external_id: this.externalAuthIdOf(identity) || undefined,
      auth_provider: this.requireWoa().authProviderDomain,
      display_name: identity.displayName?.trim() || undefined,
      ...(identity.email?.trim() ? { email: identity.email.trim() } : {}),
    };
    const created = customUserKey
      ? await this.metaKernel.invoke('user/create-with-key', { username, user_key: customUserKey, ...identityFields }, context)
      : await this.metaKernel.invoke('user/create', { username, ...identityFields }, context);
    if (created.code !== 0 || !created.data || typeof created.data !== 'object') {
      // When a custom key duplicates an existing key in the system, Core returns duplicate_user_key (409), passed through to the frontend.
      const raw = created.message || '';
      if (raw.includes('duplicate_user_key')) {
        throw new PanelAuthError('WOA_CUSTOM_KEY_DUPLICATE', 'custom user_key already exists', 409);
      }
      // user_id already exists (duplicate account creation for a same-named WOA user).
      if (raw.includes('duplicate') || raw.includes('already exists')) {
        throw new PanelAuthError('WOA_USER_ALREADY_EXISTS', 'a user with this id already exists', 409);
      }
      throw new PanelAuthError('WOA_PROVISION_FAILED', raw || 'failed to provision WOA user', 502);
    }
    const result = created.data as { user_id?: unknown; default_user_key?: unknown };
    if (typeof result.user_id !== 'string' || typeof result.default_user_key !== 'string') {
      throw new PanelAuthError('WOA_PROVISION_INVALID', 'Core returned an invalid provision response', 502);
    }
    // A newly created account must also write the external-auth association, otherwise the next login cannot find it and would be treated as first-time and ask for a key again.
    // Placed before adding to the team: the association is more fundamental than team membership, so ensure the identity chain is complete first.
    await this.bindExternalAuth(result.user_id, identity, context);
    if (this.config.woa.defaultTeamId) {
      // team-member/add requires system_admin. The credential is consistent with account creation (instance api_key),
      // using only this single source throughout, avoiding two sets of admin credentials.
      const added = await this.metaKernel.invoke('team-member/add', {
        team_id: this.config.woa.defaultTeamId,
        user_id: result.user_id,
        role: this.config.woa.defaultRole,
      }, context);
      if (added.code !== 0) {
        throw new PanelAuthError('WOA_TEAM_PROVISION_FAILED', added.message || 'failed to add WOA user to team', 502);
      }
    }
    this.identities.save({
      instanceId,
      providerId: identity.providerId,
      externalSubject: identity.subject,
      coreUserId: result.user_id,
      encryptedUserKey: encryptSecret(result.default_user_key, this.config.sessionSecret),
      displayName: identity.displayName ?? identity.loginName,
      updatedAt: new Date().toISOString(),
    });
    this.logger.info('WOA identity provisioned', {
      instanceId,
      providerId: identity.providerId,
      externalSubject: identity.subject,
      coreUserId: result.user_id,
    });
    const verified = await this.verifyCoreUser(instanceId, result.default_user_key, requestId);
    return { coreUserId: result.user_id, userKey: result.default_user_key, user: verified.user };
  }

  private saveIdentityBinding(
    ...[instanceId, identity, coreUserId, userKey]: [string, ExternalIdentity, string, string]
  ): void {
    this.identities.save({
      instanceId,
      providerId: identity.providerId,
      externalSubject: identity.subject,
      coreUserId,
      encryptedUserKey: encryptSecret(userKey, this.config.sessionSecret),
      displayName: identity.displayName ?? identity.loginName,
      updatedAt: new Date().toISOString(),
    });
  }

  private requireWoa(): HeaderInjectedProvider {
    const provider = this.providers.get('woa');
    if (!provider || provider.kind !== 'header-injected') {
      throw new PanelAuthError('AUTH_METHOD_DISABLED', 'WOA authentication is disabled', 404);
    }
    return provider as HeaderInjectedProvider;
  }

  private requireInstance(instanceId: string) {
    try {
      return this.instances.resolve(instanceId);
    } catch {
      throw new PanelAuthError('INVALID_INSTANCE', 'invalid metadata instance', 400);
    }
  }

  private context(entry: ReturnType<InstanceRegistry['resolve']>, userKey: string, requestId?: string): MetaCallContext {
    return {
      instanceId: entry.instance_id,
      gatewayEndpoint: entry.gateway_endpoint,
      gatewayApiKey: entry.api_key,
      userKey,
      reqId: requestId,
    };
  }

  private async verifyCoreUser(
    instanceId: string,
    userKey: string,
    requestId?: string,
  ): Promise<{ user_id: string; user: SessionUser }> {
    const entry = this.requireInstance(instanceId);
    const envelope = await this.metaKernel.invoke(
      'auth/verify',
      { user_key: userKey },
      this.context(entry, userKey, requestId),
    );
    return this.readVerifiedUser(envelope);
  }

  private readVerifiedUser(
    envelope: { code: number; message: string; data: unknown },
  ): { user_id: string; user: SessionUser } {
    const data = envelope.data as { valid?: boolean; user?: SessionUser } | null;
    if (
      envelope.code !== 0 ||
      data?.valid !== true ||
      !data.user ||
      typeof data.user.user_id !== 'string'
    ) {
      throw new PanelAuthError('INVALID_USER_KEY', 'user_key verification failed', 401);
    }
    return { user_id: data.user.user_id, user: data.user };
  }

  private buildCallbackUrl(instanceId: string, _returnTo: string): string {
    this.requireInstance(instanceId);
    // WOA redirects back to the APP_URL root path; identity is injected by the gateway via request headers.
    return `${this.config.woa.appUrl.replace(/\/+$/, '')}/`;
  }

  private safeReturnTo(value: string): string {
    if (!value || !value.startsWith('/') || value.startsWith('//')) return '/';
    return value;
  }
}
